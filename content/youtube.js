/**
 * Sahayak — YouTube Content Script Helper
 *
 * Responsibilities:
 *  - Detect YouTube video pages (watch, shorts, embed, live)
 *  - Extract video metadata (title, author, video ID, duration)
 *  - Retrieve and parse timed captions XML from YouTube TimedText API
 *  - Group cues into timestamped paragraphs for LLM chapter summarisation
 *  - Control playback seeking (video.currentTime = seconds)
 *
 * Edge cases covered:
 *  1.4.1 — Video has no captions (returns hasCaptions: false for URL fallback)
 *  1.4.2 — Private, unlisted-restricted, or age-gated videos
 *  1.4.3 — Livestream detection (rejects live / unended streams)
 *  1.4.4 — Long videos (>3 hours) truncated to ~25k tokens
 *  1.4.5 — Shorts URL format (/shorts/ID)
 *  1.4.6 — Embed URL format (/embed/ID)
 *  1.4.7 — Multi-language captions (picks best available track)
 *  1.4.8 — Missing video element on seek
 *  1.4.9 — Auto-generated captions marker (isAutoGenerated)
 */

(function () {
  'use strict';

  const MAX_CAPTIONS_CHAR_LENGTH = 50000; // ~12,500 words / ~15,000 tokens

  /**
   * Extract video ID from any YouTube URL format.
   * Supports: watch?v=ID, youtu.be/ID, /shorts/ID, /embed/ID, /live/ID
   */
  function extractVideoId(url) {
    if (!url) return null;
    try {
      const parsed = new URL(url);
      const hostname = parsed.hostname.toLowerCase();

      // youtu.be/ID
      if (hostname === 'youtu.be' || hostname.endsWith('.youtu.be')) {
        const id = parsed.pathname.slice(1).split('/')[0];
        return id && id.length > 0 ? id : null;
      }

      if (hostname.includes('youtube.com')) {
        // /watch?v=ID
        const v = parsed.searchParams.get('v');
        if (v) return v;

        // /shorts/ID, /embed/ID, /live/ID, /v/ID
        const pathParts = parsed.pathname.split('/').filter(Boolean);
        if (pathParts.length >= 2) {
          const prefix = pathParts[0];
          if (['shorts', 'embed', 'live', 'v'].includes(prefix)) {
            return pathParts[1];
          }
        }
      }
    } catch (e) {
      // Fallback regex if URL parsing throws
      const match = url.match(/(?:youtube\.com\/(?:watch\?.*v=|shorts\/|embed\/|live\/|v\/)|youtu\.be\/)([a-zA-Z0-9_-]{11})/);
      if (match) return match[1];
    }
    return null;
  }

  /**
   * Check whether a given URL is a YouTube page.
   */
  function isYouTubeUrl(url) {
    if (!url) return false;
    return /(?:youtube\.com\/(?:watch|shorts|embed|live)|youtu\.be\/)/i.test(url);
  }

  /**
   * Check if current page represents an active livestream.
   */
  function isLiveStream(playerResponse) {
    const url = window.location.href;
    if (url.includes('/live/') || url.includes('feature=live')) return true;

    if (playerResponse && playerResponse.videoDetails) {
      if (playerResponse.videoDetails.isLive || playerResponse.videoDetails.isLiveContent) {
        return true;
      }
    }

    // DOM badges
    const liveBadge = document.querySelector('.ytp-live, .ytp-live-badge, .badge-style-type-live-now');
    if (liveBadge && !liveBadge.classList.contains('disabled')) {
      return true;
    }

    const metaLive = document.querySelector('meta[itemprop="isLiveBroadcast"][content="True"]');
    if (metaLive) return true;

    return false;
  }

  /**
   * Balanced JSON extraction from script text.
   * Useful when JSON string has complex nested structures that regex might clip.
   */
  function extractBalancedJson(text, startIndex) {
    if (startIndex < 0) return null;
    const braceStart = text.indexOf('{', startIndex);
    if (braceStart === -1) return null;

    let depth = 0;
    let inString = false;
    let escapeNext = false;

    for (let i = braceStart; i < text.length; i++) {
      const char = text[i];

      if (escapeNext) {
        escapeNext = false;
        continue;
      }

      if (char === '\\') {
        escapeNext = true;
        continue;
      }

      if (char === '"') {
        inString = !inString;
        continue;
      }

      if (!inString) {
        if (char === '{') {
          depth++;
        } else if (char === '}') {
          depth--;
          if (depth === 0) {
            const jsonStr = text.substring(braceStart, i + 1);
            try {
              return JSON.parse(jsonStr);
            } catch (err) {
              return null;
            }
          }
        }
      }
    }
    return null;
  }

  /**
   * Inspect script tags on current page to retrieve ytInitialPlayerResponse.
   */
  function getPlayerResponseFromScripts(currentVideoId) {
    const scripts = document.querySelectorAll('script');
    for (const s of scripts) {
      const content = s.textContent || '';
      if (content.includes('ytInitialPlayerResponse')) {
        const idx = content.indexOf('ytInitialPlayerResponse');
        const parsed = extractBalancedJson(content, idx);
        if (parsed) {
          if (!currentVideoId || parsed.videoDetails?.videoId === currentVideoId) {
            return parsed;
          }
        }
      }
    }
    return null;
  }

  /**
   * Fetch current page HTML to extract ytInitialPlayerResponse.
   * Solves SPA navigation issues where DOM scripts contain the previous video.
   */
  async function fetchPlayerResponseFromPage(currentVideoId) {
    try {
      const res = await fetch(window.location.href, { credentials: 'include' });
      if (!res.ok) return null;
      const html = await res.text();
      const idx = html.indexOf('ytInitialPlayerResponse');
      if (idx !== -1) {
        const parsed = extractBalancedJson(html, idx);
        if (parsed) {
          if (!currentVideoId || parsed.videoDetails?.videoId === currentVideoId) {
            return parsed;
          }
        }
      }
    } catch (err) {
      console.warn('[Sahayak] fetchPlayerResponseFromPage error:', err);
    }
    return null;
  }

  /**
   * Get video title from page DOM or metadata.
   */
  function getVideoTitle() {
    const titleEl = document.querySelector('h1.ytd-watch-metadata yt-formatted-string, #title h1 yt-formatted-string, h1.title');
    if (titleEl && titleEl.textContent.trim()) {
      return titleEl.textContent.trim();
    }
    const metaTitle = document.querySelector('meta[name="title"]');
    if (metaTitle && metaTitle.content) {
      return metaTitle.content.trim();
    }
    return document.title.replace(/ - YouTube$/, '').trim();
  }

  /**
   * Get channel/author name from page DOM or metadata.
   */
  function getVideoAuthor() {
    const channelEl = document.querySelector('#channel-name a, ytd-channel-name a, #owner-name a');
    if (channelEl && channelEl.textContent.trim()) {
      return channelEl.textContent.trim();
    }
    const metaAuthor = document.querySelector('link[itemprop="name"]');
    if (metaAuthor && metaAuthor.getAttribute('content')) {
      return metaAuthor.getAttribute('content').trim();
    }
    return '';
  }

  /**
   * Choose the best caption track from the available tracks list.
   * Priority:
   *  1. Manual English track
   *  2. Auto-generated English track
   *  3. Manual track in any language
   *  4. First available track
   */
  function selectBestCaptionTrack(tracks) {
    if (!Array.isArray(tracks) || tracks.length === 0) return null;

    // 1. Manual English
    const manualEn = tracks.find(t => (t.languageCode === 'en' || t.languageCode?.startsWith('en')) && t.kind !== 'asr');
    if (manualEn) return manualEn;

    // 2. Auto-generated English
    const autoEn = tracks.find(t => t.languageCode === 'en' || t.languageCode?.startsWith('en'));
    if (autoEn) return autoEn;

    // 3. Any manual track
    const manualAny = tracks.find(t => t.kind !== 'asr');
    if (manualAny) return manualAny;

    // 4. Default to first track
    return tracks[0];
  }

  /**
   * Decode XML / HTML entities in caption text strings.
   */
  function decodeEntities(str) {
    if (!str) return '';
    return str
      .replace(/&amp;/g, '&')
      .replace(/&lt;/g, '<')
      .replace(/&gt;/g, '>')
      .replace(/&quot;/g, '"')
      .replace(/&#39;/g, "'")
      .replace(/&#039;/g, "'")
      .replace(/&apos;/g, "'")
      .replace(/\n+/g, ' ')
      .trim();
  }

  /**
   * Convert seconds into formatted MM:SS or HH:MM:SS.
   */
  function formatSeconds(seconds) {
    const s = Math.max(0, Math.floor(seconds));
    const hrs = Math.floor(s / 3600);
    const mins = Math.floor((s % 3600) / 60);
    const secs = s % 60;

    if (hrs > 0) {
      return `${hrs}:${String(mins).padStart(2, '0')}:${String(secs).padStart(2, '0')}`;
    }
    return `${mins}:${String(secs).padStart(2, '0')}`;
  }

  /**
   * Parse YouTube timedtext XML into structured segment cues.
   */
  function parseTimedTextXml(xmlText) {
    const parser = new DOMParser();
    const doc = parser.parseFromString(xmlText, 'text/xml');

    const cues = [];

    // Format 1: <text start="0.08" dur="4.16">...</text>
    const textNodes = doc.querySelectorAll('text');
    if (textNodes.length > 0) {
      textNodes.forEach((node) => {
        const start = parseFloat(node.getAttribute('start') || '0');
        const dur = parseFloat(node.getAttribute('dur') || '0');
        const text = decodeEntities(node.textContent);
        if (text) {
          cues.push({ start, dur, text });
        }
      });
      return cues;
    }

    // Format 2: <p t="80" d="4160">...</p>
    const pNodes = doc.querySelectorAll('p');
    if (pNodes.length > 0) {
      pNodes.forEach((node) => {
        const start = (parseInt(node.getAttribute('t') || '0', 10)) / 1000;
        const dur = (parseInt(node.getAttribute('d') || '0', 10)) / 1000;
        const text = decodeEntities(node.textContent);
        if (text) {
          cues.push({ start, dur, text });
        }
      });
      return cues;
    }

    return cues;
  }

  /**
   * Aggregate fine-grained caption cues into coherent timestamped paragraphs.
   * Emits chunks of roughly ~30-45 seconds or ~60 words.
   */
  function groupCuesIntoParagraphs(cues) {
    if (!cues || cues.length === 0) return '';

    const paragraphs = [];
    let currentStartTime = cues[0].start;
    let currentWords = [];
    let lastCueEnd = cues[0].start;

    for (let i = 0; i < cues.length; i++) {
      const cue = cues[i];
      const cueWords = cue.text.split(/\s+/).filter(Boolean);

      // Start new paragraph if duration > 35s or word count > 60, or a pause > 5s
      const timeElapsed = cue.start - currentStartTime;
      const pauseDuration = cue.start - lastCueEnd;

      if ((timeElapsed > 35 || currentWords.length > 60 || pauseDuration > 5) && currentWords.length > 0) {
        paragraphs.push(`[${formatSeconds(currentStartTime)}] ${currentWords.join(' ')}`);
        currentStartTime = cue.start;
        currentWords = [];
      }

      currentWords.push(...cueWords);
      lastCueEnd = cue.start + (cue.dur || 0);
    }

    if (currentWords.length > 0) {
      paragraphs.push(`[${formatSeconds(currentStartTime)}] ${currentWords.join(' ')}`);
    }

    return paragraphs.join('\n\n');
  }

  /**
   * Extract video captions and metadata from active YouTube tab.
   * Returns:
   *  { success: true, data: { hasCaptions: boolean, ... } }
   *  or { success: false, error: string, ... }
   */
  async function extractCaptions() {
    const videoId = extractVideoId(window.location.href);
    if (!videoId) {
      return {
        success: false,
        code: 'NOT_YOUTUBE_VIDEO',
        error: 'Current page is not an active YouTube video.'
      };
    }

    const title = getVideoTitle();
    const author = getVideoAuthor();

    // 1. Locate player response (scripts or fresh HTML)
    let playerResponse = getPlayerResponseFromScripts(videoId);
    if (!playerResponse) {
      playerResponse = await fetchPlayerResponseFromPage(videoId);
    }

    // 2. Edge case 1.4.3: Livestream check
    if (isLiveStream(playerResponse)) {
      return {
        success: false,
        code: 'LIVESTREAM_NOT_SUPPORTED',
        isLive: true,
        error: 'Live streams cannot be summarised.'
      };
    }

    // 3. Edge case 1.4.2: Playability / Restriction check
    if (playerResponse && playerResponse.playabilityStatus) {
      const status = playerResponse.playabilityStatus.status;
      if (status === 'UNPLAYABLE' || status === 'LOGIN_REQUIRED' || status === 'ERROR') {
        return {
          success: false,
          code: 'RESTRICTED_VIDEO',
          isRestricted: true,
          error: 'This video is private, restricted, or requires login. Sahayak can only summarise public YouTube videos.'
        };
      }
    }

    // 4. Locate caption tracks
    let captionTracks = playerResponse?.captions?.playerCaptionsTracklistRenderer?.captionTracks;

    // If captionTracks missing, attempt fallback timedtext list endpoint
    if (!captionTracks || captionTracks.length === 0) {
      try {
        const listUrl = `https://www.youtube.com/api/timedtext?type=list&v=${videoId}`;
        const listRes = await fetch(listUrl, { credentials: 'include' });
        if (listRes.ok) {
          const listXml = await listRes.text();
          const doc = new DOMParser().parseFromString(listXml, 'text/xml');
          const trackNodes = doc.querySelectorAll('track');
          if (trackNodes.length > 0) {
            captionTracks = Array.from(trackNodes).map((tn) => ({
              baseUrl: `https://www.youtube.com/api/timedtext?v=${videoId}&lang=${tn.getAttribute('lang_code')}`,
              languageCode: tn.getAttribute('lang_code'),
              name: { simpleText: tn.getAttribute('name') || tn.getAttribute('lang_translated') || 'Captions' },
              kind: tn.getAttribute('kind') || ''
            }));
          }
        }
      } catch (err) {
        console.warn('[Sahayak] Fallback timedtext list failed:', err);
      }
    }

    // 5. Select best caption track
    const selectedTrack = selectBestCaptionTrack(captionTracks);

    if (!selectedTrack || !selectedTrack.baseUrl) {
      // Edge case 1.4.1: No captions found — signal fallback to URL
      return {
        success: true,
        data: {
          hasCaptions: false,
          videoId,
          title,
          author,
          url: window.location.href
        }
      };
    }

    // 6. Fetch track XML
    try {
      const trackRes = await fetch(selectedTrack.baseUrl, { credentials: 'include' });
      if (!trackRes.ok) {
        throw new Error(`Timedtext HTTP ${trackRes.status}`);
      }

      const xmlText = await trackRes.text();
      const cues = parseTimedTextXml(xmlText);

      if (!cues || cues.length === 0) {
        // No parseable cues — fallback to direct URL
        return {
          success: true,
          data: {
            hasCaptions: false,
            videoId,
            title,
            author,
            url: window.location.href
          }
        };
      }

      let captionsText = groupCuesIntoParagraphs(cues);
      let isTruncated = false;

      // Edge case 1.4.4: Truncate very long transcripts (>50k chars)
      if (captionsText.length > MAX_CAPTIONS_CHAR_LENGTH) {
        captionsText = captionsText.substring(0, MAX_CAPTIONS_CHAR_LENGTH);
        const lastNewline = captionsText.lastIndexOf('\n');
        if (lastNewline > 40000) {
          captionsText = captionsText.substring(0, lastNewline);
        }
        captionsText += '\n\n[...transcript truncated to fit length limit]';
        isTruncated = true;
      }

      return {
        success: true,
        data: {
          hasCaptions: true,
          videoId,
          title,
          author,
          captionsText,
          isAutoGenerated: selectedTrack.kind === 'asr',
          isTruncated,
          url: window.location.href
        }
      };
    } catch (err) {
      console.warn('[Sahayak] Caption fetch error:', err);
      // Fallback to URL mode
      return {
        success: true,
        data: {
          hasCaptions: false,
          videoId,
          title,
          author,
          url: window.location.href
        }
      };
    }
  }

  /**
   * Jump YouTube video player to specific timestamp in seconds.
   * Edge case 1.4.8: Handles missing video element.
   */
  function seekTo(seconds) {
    const video = document.querySelector('video') || document.querySelector('.html5-main-video');
    if (!video) {
      return {
        success: false,
        code: 'VIDEO_NOT_FOUND',
        error: 'Could not find the video player on this page.'
      };
    }

    const targetTime = Math.max(0, Number(seconds) || 0);
    video.currentTime = targetTime;

    if (video.paused) {
      video.play().catch(() => {});
    }

    return {
      success: true,
      currentTime: video.currentTime
    };
  }

  // Export globally
  const SahayakYouTube = {
    extractVideoId,
    isYouTubeUrl,
    extractCaptions,
    seekTo,
    formatSeconds
  };

  globalThis.SahayakYouTube = SahayakYouTube;
  if (typeof window !== 'undefined') {
    window.SahayakYouTube = SahayakYouTube;
  }
})();

