/**
 * Sahayak — Prompt Builder Service
 *
 * Centralises system and user prompt construction for AI tasks.
 * Handles language adapters (English / Hinglish), formatting rules,
 * and structured output schemas.
 */

(function () {
  'use strict';

  /**
   * Get system prompt language instruction.
   *
   * @param {string} [language='en'] - 'en' or 'hi-en'
   * @returns {string}
   */
  function getLanguageInstruction(language = 'en') {
    if (language === 'hi-en' || language === 'hi') {
      return (
        'Respond in Hinglish — natural Hindi-English mix written strictly in Roman script. ' +
        'Keep technical and domain-specific terms in English. ' +
        'CRITICAL: You MUST write in Roman script only. Do NOT use Devanagari (Hindi script). ' +
        "Example: 'Yeh bahut accha hai' NOT 'यह बहुत अच्छा है'. " +
        "Example tone: 'Is article ka main point yeh hai ki...', 'Pehla key point yeh hai ki...', 'Is video me explain kiya gaya hai ki...'."
      );
    }
    return 'Respond in clear, concise English.';
  }

  /**
   * Build the prompt for structured article summarisation.
   *
   * @param {Object} article
   * @param {string} article.title
   * @param {string} article.content
   * @param {string} [article.byline]
   * @param {string} [article.siteName]
   * @param {string} [article.url]
   * @param {boolean} [article.isTruncated]
   * @param {string} [language='en']
   * @returns {{ systemPrompt: string, userPrompt: string }}
   */
  function buildSummaryPrompt(article, language = 'en') {
    const langRule = getLanguageInstruction(language);

    const systemPrompt = [
      'You are Sahayak, an intelligent, objective browser assistant that helps users quickly grasp web articles.',
      langRule,
      'Maintain an informative, neutral tone. Ground all statements strictly in the article provided.',
      'Do not invent facts or extrapolate beyond what the text states.'
    ].join(' ');

    const metadataLines = [];
    if (article.title) metadataLines.push(`Title: ${article.title}`);
    if (article.siteName) metadataLines.push(`Source: ${article.siteName}`);
    if (article.byline) metadataLines.push(`Byline: ${article.byline}`);
    if (article.url) metadataLines.push(`URL: ${article.url}`);
    if (article.isTruncated) {
      metadataLines.push('Note: This article is very long and has been truncated to fit.');
    }

    const languageInstructionBlock = language === 'hi-en'
      ? 'CRITICAL FORMATTING INSTRUCTION: Keep the exact Markdown section titles (## TL;DR, ## Key Points, ## What To Do Next) in English so the application interface can parse them. Write the explanation text, list items, and next steps in natural Roman-script Hinglish.'
      : '';

    const userPrompt = [
      'Please read the following article extract and provide a structured summary.',
      '',
      metadataLines.join('\n'),
      '',
      '--- Article Content Start ---',
      article.content,
      '--- Article Content End ---',
      '',
      languageInstructionBlock,
      '',
      'Format your response strictly using the following three Markdown sections:',
      '',
      '## TL;DR',
      language === 'hi-en'
        ? 'One direct, punchy sentence in Roman-script Hinglish summarising the primary conclusion or theme of the article.'
        : 'One direct, punchy sentence summarising the primary conclusion or theme of the article.',
      '',
      '## Key Points',
      '1. [First major insight or fact]',
      '2. [Second major insight or fact]',
      '3. [Third major insight or fact]',
      '4. [Fourth major insight or fact]',
      '5. [Fifth major insight or fact]',
      '',
      '## What To Do Next',
      'Provide 2 to 3 concrete, practical recommendations, next steps, or discussion angles for someone reading this topic.'
    ].filter(Boolean).join('\n');

    return {
      systemPrompt,
      userPrompt
    };
  }

  /**
   * Build the prompt for structured YouTube video summarisation.
   * Produces TL;DR, chapter-by-chapter notes with clickable timestamps, and key takeaways.
   *
   * @param {Object} videoData
   * @param {string} [videoData.videoId]
   * @param {string} [videoData.title]
   * @param {string} [videoData.author]
   * @param {string} [videoData.url]
   * @param {string} [videoData.captionsText]
   * @param {boolean} [videoData.hasCaptions]
   * @param {boolean} [videoData.isAutoGenerated]
   * @param {boolean} [videoData.isTruncated]
   * @param {string} [language='en']
   * @returns {{ systemPrompt: string, userPrompt: string }}
   */
  function buildYouTubePrompt(videoData, language = 'en') {
    const langRule = getLanguageInstruction(language);

    const systemPrompt = [
      'You are Sahayak, an intelligent, objective browser assistant that creates precise chapter notes and key takeaways for YouTube videos.',
      langRule,
      'Maintain an informative, neutral tone. Ground all notes strictly in the video content.',
      'Do not invent facts, timestamps, or extrapolate beyond what is presented in the video.'
    ].join(' ');

    const metadataLines = [];
    if (videoData.title) metadataLines.push(`Video Title: ${videoData.title}`);
    if (videoData.author) metadataLines.push(`Channel / Creator: ${videoData.author}`);
    if (videoData.url) metadataLines.push(`Video URL: ${videoData.url}`);
    if (videoData.isAutoGenerated) {
      metadataLines.push('Note: Captions are auto-generated speech recognition and may have minor transcription anomalies.');
    }
    if (videoData.isTruncated) {
      metadataLines.push('Note: This video is very long; transcript covers the first portion.');
    }

    let contentBlock = '';
    if (videoData.hasCaptions && videoData.captionsText) {
      contentBlock = [
        '--- Video Transcript Start ---',
        videoData.captionsText,
        '--- Video Transcript End ---'
      ].join('\n');
    } else {
      contentBlock = `Please inspect the public video at URL: ${videoData.url || 'the current YouTube page'}.`;
    }

    const videoUrlBase = videoData.url || (videoData.videoId ? `https://www.youtube.com/watch?v=${videoData.videoId}` : 'https://www.youtube.com/watch?v=');

    const languageInstructionBlock = language === 'hi-en'
      ? 'CRITICAL FORMATTING INSTRUCTION: Keep the exact Markdown section titles (## TL;DR, ## Chapters & Timestamps, ## Key Takeaways) in English. Keep timestamp format [MM:SS] exactly as shown. Write the chapter descriptions and takeaways in natural Roman-script Hinglish.'
      : '';

    const userPrompt = [
      'Please analyze this YouTube video and produce a structured chapter-by-chapter summary with clickable timestamps.',
      '',
      metadataLines.join('\n'),
      '',
      contentBlock,
      '',
      languageInstructionBlock,
      '',
      'Format your response strictly using the following Markdown sections:',
      '',
      '## TL;DR',
      language === 'hi-en'
        ? 'One to two direct, punchy sentences in Roman-script Hinglish capturing the primary thesis or value of the video.'
        : 'One to two direct, punchy sentences capturing the primary thesis or value of the video.',
      '',
      '## Chapters & Timestamps',
      'Provide chronological chapter notes for key milestones, topic changes, and major points.',
      `Each chapter bullet MUST start with a timestamp link in the exact format [MM:SS](${videoUrlBase}&t=Ns) or [HH:MM:SS](${videoUrlBase}&t=Ns), where N is the total elapsed time in seconds.`,
      'Follow each timestamp with a bold topic heading and a concise 1-2 sentence description of what is explained in that segment.',
      'Example formatting:',
      `- [0:00](${videoUrlBase}&t=0s) **Introduction and Overview**: Setting up the problem and core goals.`,
      `- [2:14](${videoUrlBase}&t=134s) **Core Concept**: Detailed explanation of the primary architecture.`,
      `- [5:30](${videoUrlBase}&t=330s) **Live Demo Walkthrough**: Concrete walkthrough of the system in action.`,
      '',
      '## Key Takeaways',
      '1. [First major takeaway or lesson from the video]',
      '2. [Second major takeaway or lesson from the video]',
      '3. [Third major takeaway or lesson from the video]',
      '4. [Fourth major takeaway or lesson from the video]',
      '5. [Fifth major takeaway or lesson from the video]'
    ].filter(Boolean).join('\n');

    return {
      systemPrompt,
      userPrompt
    };
  }

  /**
   * Split long document text into overlapping chunks and pick the most query-relevant chunks.
   * Architecture §8.3 & Slice 2.1 step 5.
   */
  function chunkAndSelectContext(text, query, maxChars = 65000) {
    if (!text || text.length <= maxChars) {
      return text;
    }

    const chunkSize = 12000;
    const overlap = 1000;
    const chunks = [];
    let start = 0;

    while (start < text.length) {
      const end = Math.min(start + chunkSize, text.length);
      chunks.push(text.substring(start, end));
      if (end === text.length) break;
      start += (chunkSize - overlap);
    }

    if (chunks.length <= 4) {
      return text.substring(0, maxChars) + '\n\n[...truncated to fit token limit]';
    }

    const stopWords = new Set(['the', 'and', 'for', 'are', 'this', 'that', 'with', 'from', 'what', 'when', 'where', 'which', 'who', 'how', 'why', 'can', 'you', 'page', 'about']);
    const queryTerms = (query || '').toLowerCase().match(/\b[a-z0-9_]{3,}\b/g) || [];
    const validTerms = queryTerms.filter(t => !stopWords.has(t));

    const scored = chunks.map((chunk, idx) => {
      const lower = chunk.toLowerCase();
      let score = 0;
      if (idx === 0) score += 3; // Initial overview bonus
      for (const term of validTerms) {
        const matches = lower.split(term).length - 1;
        score += Math.min(matches, 10);
      }
      return { idx, chunk, score };
    });

    scored.sort((a, b) => b.score - a.score);
    const selected = scored.slice(0, 4);
    selected.sort((a, b) => a.idx - b.idx); // Preserve reading order

    const contextText = selected.map(s => s.chunk).join('\n\n[...]\n\n');
    return `Note: This is a partial extract of a long page, focused on sections most relevant to your question.\n\n${contextText}`;
  }

  /**
   * Format the last N conversation turns for grounding context.
   * Edge case 2.1.3: limits history to last 8 turns to preserve context budget.
   */
  function formatConversationHistory(history = [], maxTurns = 8) {
    if (!Array.isArray(history) || history.length === 0) return '';

    const recent = history.slice(-maxTurns);
    const formatted = recent.map(turn => {
      const speaker = turn.role === 'user' ? 'User' : 'Assistant';
      return `${speaker}: ${turn.text || ''}`;
    }).join('\n\n');

    return formatted ? `CONVERSATION HISTORY:\n${formatted}\n` : '';
  }

  /**
   * Build grounded chat prompt with strict anti-hallucination rules.
   * Architecture §8.2.
   *
   * @param {Object} pageContext
   * @param {string} pageContext.title
   * @param {string} pageContext.url
   * @param {string} pageContext.content
   * @param {string} question
   * @param {Array<Object>} [history=[]]
   * @param {string} [language='en']
   * @returns {{ systemPrompt: string, userPrompt: string }}
   */
  function buildGroundedChatPrompt(pageContext, question, history = [], language = 'en') {
    const langRule = getLanguageInstruction(language);

    const systemPrompt = [
      'You are Sahayak, an intelligent browser assistant.',
      'Answer the user\'s question using ONLY the text provided in <PAGE_CONTEXT>.',
      'Do not use outside knowledge or extrapolate beyond the provided text.',
      'If the answer cannot be found in the page context, you MUST respond exactly:',
      '"This information is not available on the current page."',
      langRule
    ].join(' ');

    // Clean user question & truncate to 500 words (Edge case 2.1.4)
    let cleanQuestion = (question || '').trim();
    const words = cleanQuestion.split(/\s+/).filter(Boolean);
    if (words.length > 500) {
      cleanQuestion = words.slice(0, 500).join(' ') + '\n\n[Note: Your question was trimmed to 500 words.]';
    }

    const fullText = pageContext.content || pageContext.textContent || '';
    const selectedContext = chunkAndSelectContext(fullText, cleanQuestion);

    const metadata = [];
    if (pageContext.title) metadata.push(`Title: ${pageContext.title}`);
    if (pageContext.url) metadata.push(`URL: ${pageContext.url}`);

    const historyBlock = formatConversationHistory(history, 8);

    const userPrompt = [
      '<PAGE_CONTEXT>',
      metadata.join('\n'),
      '',
      selectedContext,
      '</PAGE_CONTEXT>',
      '',
      historyBlock,
      'USER QUESTION:',
      cleanQuestion,
      '',
      'Remember: Answer strictly using facts stated in <PAGE_CONTEXT>. If not present, state that the information is not available on the current page.'
    ].filter(Boolean).join('\n');

    return {
      systemPrompt,
      userPrompt
    };
  }

  /**
   * Build prompt for explaining selected text (Slice 2.2).
   *
   * @param {string} text
   * @param {string} [language='en']
   * @returns {{ systemPrompt: string, userPrompt: string }}
   */
  function buildExplainPrompt(text, language = 'en') {
    const langRule = getLanguageInstruction(language);
    const systemPrompt = `You are Sahayak, an intelligent, helpful browser assistant. ${langRule}`;
    const userPrompt = `Explain the following in simple, plain language:\n\n${text}`;

    return { systemPrompt, userPrompt };
  }

  /**
   * Build prompt for translating selected text (Slice 2.2).
   *
   * @param {string} text
   * @param {string} [language='en']
   * @returns {{ systemPrompt: string, userPrompt: string }}
   */
  function buildTranslatePrompt(text, language = 'en') {
    let systemPrompt;
    let userPrompt;

    if (language === 'hi-en') {
      systemPrompt =
        'You are Sahayak, an expert bilingual translator. ' +
        'Translate the text into natural Roman-script Hinglish (Hindi-English mix written strictly in Latin script). ' +
        'Keep technical, brand, and domain-specific terms in English. Do NOT use Devanagari script.';
      userPrompt = `Translate the following into Roman-script Hinglish:\n\n${text}`;
    } else {
      systemPrompt =
        'You are Sahayak, an expert bilingual translator. ' +
        'Translate the text accurately, clearly, and naturally into Hindi. Preserve original meaning and tone.';
      userPrompt = `Translate the following into Hindi:\n\n${text}`;
    }

    return { systemPrompt, userPrompt };
  }

  /**
   * Build prompt for drafting a reply to selected message (Slice 2.2 & Edge case 2.2.5).
   *
   * @param {string} text
   * @param {string} [language='en']
   * @returns {{ systemPrompt: string, userPrompt: string }}
   */
  function buildDraftReplyPrompt(text, language = 'en') {
    const langRule = getLanguageInstruction(language);
    const systemPrompt = `You are Sahayak, an expert communication assistant. ${langRule}`;

    const userPrompt = [
      'Draft a polite, professional reply to the following message:',
      '',
      text,
      '',
      'Note: If the text does not appear to be a message, provide a thoughtful, helpful response to the topic instead.'
    ].join('\n');

    return { systemPrompt, userPrompt };
  }

  /**
   * Generic router for context menu actions (Slice 2.2).
   *
   * @param {string} action - 'explain' | 'translate' | 'draft_reply' | 'draft-reply'
   * @param {string} text
   * @param {string} [language='en']
   * @returns {{ systemPrompt: string, userPrompt: string }}
   */
  function buildContextActionPrompt(action, text, language = 'en') {
    const normalized = (action || '').toLowerCase().replace(/-/g, '_');
    switch (normalized) {
      case 'explain':
        return buildExplainPrompt(text, language);
      case 'translate':
        return buildTranslatePrompt(text, language);
      case 'draft_reply':
      case 'draftreply':
        return buildDraftReplyPrompt(text, language);
      default:
        return buildExplainPrompt(text, language);
    }
  }

  // Export
  globalThis.PromptBuilder = {
    getLanguageInstruction,
    buildSummaryPrompt,
    buildYouTubePrompt,
    buildGroundedChatPrompt,
    buildExplainPrompt,
    buildTranslatePrompt,
    buildDraftReplyPrompt,
    buildContextActionPrompt,
    chunkAndSelectContext,
    formatConversationHistory
  };
})();

